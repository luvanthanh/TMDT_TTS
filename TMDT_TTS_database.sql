-- TMDT_TTS - E-commerce database schema
-- Database: PostgreSQL 14+
-- Quy uoc: cac cot duoc dat ten theo dang <ten_thuc_the>_<thuoc_tinh>.
-- Vi du: user_name, product_price, order_status.
-- Chay script trong database tmdt_tts da duoc tao san.

BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(150) NOT NULL,
    user_email VARCHAR(255) NOT NULL UNIQUE,
    user_phone VARCHAR(30),
    user_password_hash VARCHAR(255) NOT NULL,
    user_role VARCHAR(20) NOT NULL DEFAULT 'CUSTOMER'
        CHECK (user_role IN ('CUSTOMER', 'ADMIN')),
    user_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (user_status IN ('ACTIVE', 'INACTIVE', 'LOCKED')),
    user_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    user_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    address_recipient_name VARCHAR(150) NOT NULL,
    address_phone VARCHAR(30) NOT NULL,
    address_detail VARCHAR(255) NOT NULL,
    address_ward VARCHAR(100),
    address_district VARCHAR(100),
    address_city VARCHAR(100) NOT NULL,
    address_postal_code VARCHAR(20),
    address_is_default BOOLEAN NOT NULL DEFAULT FALSE,
    address_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_parent_id BIGINT REFERENCES categories(category_id) ON DELETE SET NULL,
    category_name VARCHAR(120) NOT NULL,
    category_slug VARCHAR(150) NOT NULL UNIQUE,
    category_description TEXT,
    category_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (category_status IN ('ACTIVE', 'INACTIVE')),
    category_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_category_id BIGINT REFERENCES categories(category_id) ON DELETE SET NULL,
    product_name VARCHAR(255) NOT NULL,
    product_slug VARCHAR(280) NOT NULL UNIQUE,
    product_description TEXT,
    product_price NUMERIC(12,2) NOT NULL CHECK (product_price >= 0),
    product_sale_price NUMERIC(12,2)
        CHECK (product_sale_price IS NULL OR product_sale_price >= 0),
    product_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (product_status IN ('DRAFT', 'ACTIVE', 'INACTIVE', 'OUT_OF_STOCK')),
    product_is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    product_is_flash_sale BOOLEAN NOT NULL DEFAULT FALSE,
    product_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    product_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (product_sale_price IS NULL OR product_sale_price <= product_price)
);
CREATE TABLE IF NOT EXISTS product_images (
    product_image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_image_product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    product_image_url TEXT NOT NULL,
    product_image_alt_text VARCHAR(255),
    product_image_is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    product_image_sort_order INTEGER NOT NULL DEFAULT 0 CHECK (product_image_sort_order >= 0),
    product_image_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Moi bien the co ton kho rieng theo mau sac/kich thuoc.
-- San pham khong co tuy chon van can mot bien the mac dinh.
CREATE TABLE IF NOT EXISTS product_variants (
    product_variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_variant_product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    product_variant_sku VARCHAR(100) NOT NULL UNIQUE,
    product_variant_color VARCHAR(80),
    product_variant_size VARCHAR(80),
    product_variant_price_override NUMERIC(12,2)
        CHECK (product_variant_price_override IS NULL OR product_variant_price_override >= 0),
    product_variant_stock_quantity INTEGER NOT NULL DEFAULT 0
        CHECK (product_variant_stock_quantity >= 0),
    product_variant_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (product_variant_status IN ('ACTIVE', 'INACTIVE')),
    product_variant_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS carts (
    cart_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    cart_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cart_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS cart_items (
    cart_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_item_cart_id BIGINT NOT NULL REFERENCES carts(cart_id) ON DELETE CASCADE,
    cart_item_product_variant_id BIGINT NOT NULL
        REFERENCES product_variants(product_variant_id) ON DELETE RESTRICT,
    cart_item_quantity INTEGER NOT NULL CHECK (cart_item_quantity > 0),
    cart_item_added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (cart_item_cart_id, cart_item_product_variant_id)
);
CREATE TABLE IF NOT EXISTS wishlists (
    wishlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wishlist_user_id BIGINT NOT NULL UNIQUE REFERENCES users(user_id) ON DELETE CASCADE,
    wishlist_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS wishlist_items (
    wishlist_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wishlist_item_wishlist_id BIGINT NOT NULL REFERENCES wishlists(wishlist_id) ON DELETE CASCADE,
    wishlist_item_product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    wishlist_item_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (wishlist_item_wishlist_id, wishlist_item_product_id)
);
CREATE TABLE IF NOT EXISTS coupons (
    coupon_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_code VARCHAR(50) NOT NULL UNIQUE,
    coupon_description TEXT,
    coupon_discount_type VARCHAR(20) NOT NULL
        CHECK (coupon_discount_type IN ('PERCENT', 'FIXED')),
    coupon_discount_value NUMERIC(12,2) NOT NULL CHECK (coupon_discount_value > 0),
    coupon_min_order_amount NUMERIC(12,2) NOT NULL DEFAULT 0
        CHECK (coupon_min_order_amount >= 0),
    coupon_max_discount_amount NUMERIC(12,2)
        CHECK (coupon_max_discount_amount IS NULL OR coupon_max_discount_amount >= 0),
    coupon_start_at TIMESTAMPTZ,
    coupon_end_at TIMESTAMPTZ,
    coupon_usage_limit INTEGER CHECK (coupon_usage_limit IS NULL OR coupon_usage_limit > 0),
    coupon_used_count INTEGER NOT NULL DEFAULT 0 CHECK (coupon_used_count >= 0),
    coupon_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (coupon_status IN ('ACTIVE', 'INACTIVE')),
    CHECK (coupon_end_at IS NULL OR coupon_start_at IS NULL OR coupon_end_at > coupon_start_at),
    CHECK (coupon_discount_type <> 'PERCENT' OR coupon_discount_value <= 100)
);

CREATE TABLE IF NOT EXISTS orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code VARCHAR(40) NOT NULL UNIQUE,
    order_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    order_coupon_id BIGINT REFERENCES coupons(coupon_id) ON DELETE SET NULL,
    order_coupon_code_snapshot VARCHAR(50),
    order_recipient_name VARCHAR(150) NOT NULL,
    order_recipient_phone VARCHAR(30) NOT NULL,
    order_shipping_address TEXT NOT NULL,
    order_subtotal NUMERIC(12,2) NOT NULL CHECK (order_subtotal >= 0),
    order_discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (order_discount_amount >= 0),
    order_shipping_fee NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (order_shipping_fee >= 0),
    order_total_amount NUMERIC(12,2) NOT NULL CHECK (order_total_amount >= 0),
    order_payment_method VARCHAR(30) NOT NULL DEFAULT 'COD'
        CHECK (order_payment_method IN ('COD', 'BANK_TRANSFER')),
    order_payment_status VARCHAR(30) NOT NULL DEFAULT 'UNPAID'
        CHECK (order_payment_status IN ('UNPAID', 'PENDING', 'PAID', 'FAILED', 'REFUNDED')),
    order_status VARCHAR(30) NOT NULL DEFAULT 'PENDING'
        CHECK (order_status IN (
            'PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPED',
            'DELIVERED', 'CANCELLED', 'RETURN_REQUESTED', 'RETURNED'
        )),
    order_customer_note TEXT,
    order_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    order_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    order_item_product_variant_id BIGINT
        REFERENCES product_variants(product_variant_id) ON DELETE SET NULL,
    order_item_product_name VARCHAR(255) NOT NULL,
    order_item_sku_snapshot VARCHAR(100),
    order_item_variant_snapshot VARCHAR(180),
    order_item_unit_price NUMERIC(12,2) NOT NULL CHECK (order_item_unit_price >= 0),
    order_item_quantity INTEGER NOT NULL CHECK (order_item_quantity > 0),
    order_item_line_total NUMERIC(12,2) NOT NULL CHECK (order_item_line_total >= 0)
);
CREATE TABLE IF NOT EXISTS order_status_history (
    order_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_status_history_order_id BIGINT NOT NULL
        REFERENCES orders(order_id) ON DELETE CASCADE,
    order_status_history_old_status VARCHAR(30),
    order_status_history_new_status VARCHAR(30) NOT NULL,
    order_status_history_note TEXT,
    order_status_history_changed_by_user_id BIGINT
        REFERENCES users(user_id) ON DELETE SET NULL,
    order_status_history_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS coupon_redemptions (
    coupon_redemption_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coupon_redemption_coupon_id BIGINT NOT NULL REFERENCES coupons(coupon_id) ON DELETE RESTRICT,
    coupon_redemption_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    coupon_redemption_order_id BIGINT NOT NULL UNIQUE
        REFERENCES orders(order_id) ON DELETE CASCADE,
    coupon_redemption_redeemed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_reviews (
    product_review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_review_product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    product_review_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    product_review_order_item_id BIGINT REFERENCES order_items(order_item_id) ON DELETE SET NULL,
    product_review_rating SMALLINT NOT NULL CHECK (product_review_rating BETWEEN 1 AND 5),
    product_review_title VARCHAR(180),
    product_review_content TEXT,
    product_review_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (product_review_status IN ('PENDING', 'APPROVED', 'REJECTED')),
    product_review_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS returns (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_order_id BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    return_user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    return_reason TEXT NOT NULL,
    return_status VARCHAR(30) NOT NULL DEFAULT 'REQUESTED'
        CHECK (return_status IN ('REQUESTED', 'APPROVED', 'REJECTED', 'RECEIVED', 'REFUNDED', 'CANCELLED')),
    return_admin_note TEXT,
    return_requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    return_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS return_items (
    return_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_item_return_id BIGINT NOT NULL REFERENCES returns(return_id) ON DELETE CASCADE,
    return_item_order_item_id BIGINT NOT NULL
        REFERENCES order_items(order_item_id) ON DELETE RESTRICT,
    return_item_quantity INTEGER NOT NULL CHECK (return_item_quantity > 0),
    UNIQUE (return_item_return_id, return_item_order_item_id)
);

CREATE TABLE IF NOT EXISTS contact_messages (
    contact_message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contact_message_full_name VARCHAR(150) NOT NULL,
    contact_message_email VARCHAR(255) NOT NULL,
    contact_message_phone VARCHAR(30),
    contact_message_subject VARCHAR(200),
    contact_message_content TEXT NOT NULL,
    contact_message_status VARCHAR(20) NOT NULL DEFAULT 'NEW'
        CHECK (contact_message_status IN ('NEW', 'IN_PROGRESS', 'RESOLVED', 'SPAM')),
    contact_message_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
    newsletter_subscriber_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    newsletter_subscriber_email VARCHAR(255) NOT NULL UNIQUE,
    newsletter_subscriber_status VARCHAR(20) NOT NULL DEFAULT 'SUBSCRIBED'
        CHECK (newsletter_subscriber_status IN ('SUBSCRIBED', 'UNSUBSCRIBED')),
    newsletter_subscriber_subscribed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    newsletter_subscriber_unsubscribed_at TIMESTAMPTZ
);

COMMIT;

